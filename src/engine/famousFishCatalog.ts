export function createSpeciesConfigFromFamousFish(
  template: FamousAquariumFishTemplate
): SpeciesConfig {
  return {
    id: template.id,
    name: template.name,
    scientificName: template.scientificName,
    description: template.description,
    category: template.category,
    requiredOwnerLevel: template.requiredOwnerLevel,
    shopPriceCredits: template.shopPriceCredits,
    bodyStyle: template.bodyStyle,
    primaryColorHex: template.primaryColorHex,
    secondaryColorHex: template.secondaryColorHex,
    accentColorHex: template.accentColorHex,
    activeBaseModelVersion: 'v1.0-base',
    lifespan: {
      lifespanSimHours: template.lifespanSimHours,
      growthRatePerHour: Number((1.0 / Math.max(2, template.sexualMaturityAgeHours)).toFixed(2)),
      juvenileDurationHours: Number((template.sexualMaturityAgeHours * 0.85).toFixed(1)),
      sexualMaturityAgeHours: template.sexualMaturityAgeHours,
      reproductionIntervalHours: template.reproductionIntervalHours,
      maxReproductiveAgeHours: Number((template.lifespanSimHours * 0.85).toFixed(1)),
      minEnergyToReproduceRatio: 0.58,
      eggIncubationHours: template.eggIncubationHours,
      offspringIndependenceHours: Number((template.eggIncubationHours * 1.4).toFixed(1)),
      feedingIntervalHours: 2.0,
      metabolismEnergyPerHour: template.metabolismEnergyPerHour,
      agingRateMultiplier: 1.0,
      recoverySpeedPerHour: 9.5,
      speciesTimeMultiplier: 1.0,
    },
    baseBrainConfig: {
      ...DEFAULT_BRAIN_CONFIG,
      aggressiveness: template.aggressiveness ?? 0,
    },
  };
}
